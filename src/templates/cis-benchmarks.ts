export const ALL_CIS_CONTROLS: CISControl[] = [
  ...CIS_AWS_CONTROLS,
  ...CIS_AZURE_CONTROLS,
  ...CIS_GCP_CONTROLS,
];

// ============================================
// Utility Functions
// ============================================

export function getCISControlsByBenchmark(benchmark: CISControl['benchmark']): CISControl[] {
  return ALL_CIS_CONTROLS.filter(c => c.benchmark === benchmark);
}

export function getCISControlsBySOC2Mapping(soc2ControlId: string): CISControl[] {
  return ALL_CIS_CONTROLS.filter(c => c.soc2Mappings.includes(soc2ControlId));
}

export function getCISControlsBySeverity(severity: CISControl['severity']): CISControl[] {
  return ALL_CIS_CONTROLS.filter(c => c.severity === severity);
}

export function getAutomatedCISControls(): CISControl[] {
  return ALL_CIS_CONTROLS.filter(c => c.automated);
}

export function getCISStats(): { total: number; automated: number; manual: number; byBenchmark: Record<string, number>; bySeverity: Record<string, number> } {
  const byBenchmark: Record<string, number> = {};
  const bySeverity: Record<string, number> = {};

  for (const control of ALL_CIS_CONTROLS) {
    byBenchmark[control.benchmark] = (byBenchmark[control.benchmark] || 0) + 1;
    bySeverity[control.severity] = (bySeverity[control.severity] || 0) + 1;
  }

  return {
    total: ALL_CIS_CONTROLS.length,
    automated: ALL_CIS_CONTROLS.filter(c => c.automated).length,
    manual: ALL_CIS_CONTROLS.filter(c => !c.automated).length,
    byBenchmark,
    bySeverity,
  };
}

export function validateCISControl(control: unknown): CISControl {
  return CISControlSchema.parse(control);
}
